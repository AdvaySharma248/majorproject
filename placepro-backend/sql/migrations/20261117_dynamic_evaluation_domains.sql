BEGIN;

CREATE TABLE IF NOT EXISTS evaluation_domains (
  domain_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain_code VARCHAR(40) NULL,
  name VARCHAR(100) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS evaluation_domains_name_normalized_unique
  ON evaluation_domains (lower(btrim(name)));
CREATE UNIQUE INDEX IF NOT EXISTS evaluation_domains_code_normalized_unique
  ON evaluation_domains (lower(btrim(domain_code))) WHERE domain_code IS NOT NULL;

INSERT INTO evaluation_domains (domain_code, name, description)
SELECT seed.domain_code, seed.name, ''
FROM (VALUES
  ('programming_dsa', 'Programming/DSA'),
  ('core_computer_science', 'Core Computer Science'),
  ('software_development', 'Software Development'),
  ('employability_soft_skills', 'Employability & Soft Skills')
) AS seed(domain_code, name)
WHERE NOT EXISTS (
  SELECT 1 FROM evaluation_domains existing WHERE lower(btrim(existing.name)) = lower(btrim(seed.name))
);

ALTER TABLE skill_taxonomy ADD COLUMN IF NOT EXISTS domain_id BIGINT;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'skill_taxonomy' AND column_name = 'domain_category'
  ) THEN
    EXECUTE $migrate$
      INSERT INTO evaluation_domains (name, description)
      SELECT DISTINCT domain_category::text, '' FROM skill_taxonomy
      WHERE domain_category IS NOT NULL
        AND NOT EXISTS (
          SELECT 1 FROM evaluation_domains d WHERE lower(btrim(d.name)) = lower(btrim(skill_taxonomy.domain_category::text))
        )
    $migrate$;
    EXECUTE $migrate$
      UPDATE skill_taxonomy st SET domain_id = d.domain_id
      FROM evaluation_domains d
      WHERE st.domain_id IS NULL AND lower(btrim(d.name)) = lower(btrim(st.domain_category::text))
    $migrate$;
  END IF;

  IF EXISTS (SELECT 1 FROM skill_taxonomy WHERE domain_id IS NULL) THEN
    RAISE EXCEPTION 'Dynamic domain migration could not map every skill to a domain';
  END IF;
END $$;

ALTER TABLE skill_taxonomy ALTER COLUMN domain_id SET NOT NULL;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'skill_taxonomy_domain_id_fkey'
  ) THEN
    ALTER TABLE skill_taxonomy ADD CONSTRAINT skill_taxonomy_domain_id_fkey
      FOREIGN KEY (domain_id) REFERENCES evaluation_domains(domain_id) ON DELETE RESTRICT;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS idx_skill_taxonomy_domain_id ON skill_taxonomy(domain_id);

ALTER TABLE skill_taxonomy DROP COLUMN IF EXISTS domain_category;
DROP TYPE IF EXISTS skill_domain;

COMMIT;
